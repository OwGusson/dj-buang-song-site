create role anon;
create role authenticated;
create role service_role bypassrls;
create schema auth;
grant usage on schema auth, public to anon, authenticated, service_role;
create function auth.jwt() returns jsonb language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb;
$$;
create table public.song_requests (
 id bigint generated by default as identity primary key, created_at timestamptz default now(),
 requester_name text default '', email text default '', song_name text default '',
 artist_name text default '', notes text default '', status text default 'pending',
 details text default '', notify boolean default false, delivery text default 'public', linked_song_id text default ''
);
create table public.private_messages (
 id bigint generated by default as identity primary key, created_at timestamptz default now(),
 sender_name text default '', email text default '', message text default '', status text default 'new', sender_email text default ''
);
create table public.song_likes (song_id text primary key, likes integer default 0, updated_at timestamptz default now());
create table public.song_analytics (
 song_id text primary key, opens integer default 0, plays integer default 0, updated_at timestamptz default now(),
 unique_opens integer default 0, unique_listeners integer default 0, play_25_count integer default 0,
 song_downloads integer default 0, lyrics_downloads integer default 0
);
create table public.songs_backup (
 song_id text primary key, title text not null, artist text, requested_by text, cover_url text, audio_url text,
 lyrics text, likes integer default 0, featured boolean default false, visibility text default 'public',
 status text default 'published', created_at timestamptz, updated_at timestamptz default now(), sort_order integer default 0
);
create table public.song_events (
 id bigint generated by default as identity primary key, song_id text not null, event_type text not null,
 listener_id text, progress_percent numeric, created_at timestamptz default now()
);
grant all on all tables in schema public to anon, authenticated, service_role;
grant usage, select on all sequences in schema public to anon, authenticated, service_role;
